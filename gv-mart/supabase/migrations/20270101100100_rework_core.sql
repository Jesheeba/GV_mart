-- ── 2. Guard: rework columns change only inside SECURITY DEFINER functions ──────────────────────────
-- Ops staff may write service_tickets directly (service_tickets_write_ops). Without this, a direct API
-- update could move the responsible technician (shifting a penalty) or flip the outcome. Inside a
-- SECURITY DEFINER function current_user is the owner, not 'authenticated', so the RPCs pass.
create or replace function public._trg_service_tickets_rework_guard()
returns trigger language plpgsql set search_path = public as $$
begin
  if current_user in ('authenticated', 'anon') and (
       new.rework_of_ticket_id is distinct from old.rework_of_ticket_id
    or new.rework_responsible_technician_id is distinct from old.rework_responsible_technician_id
    or new.rework_reason is distinct from old.rework_reason
    or new.rework_raised_by is distinct from old.rework_raised_by
    or new.rework_raised_at is distinct from old.rework_raised_at
    or new.rework_outcome is distinct from old.rework_outcome
    or new.rework_escalation_reason is distinct from old.rework_escalation_reason
    or ((new.type::text = 'rework') is distinct from (old.type::text = 'rework'))
  ) then
    raise exception 'service_tickets: rework fields can only be changed through the rework actions';
  end if;
  return new;
end $$;

drop trigger if exists service_tickets_rework_guard on public.service_tickets;
create trigger service_tickets_rework_guard before update on public.service_tickets
  for each row execute function public._trg_service_tickets_rework_guard();

