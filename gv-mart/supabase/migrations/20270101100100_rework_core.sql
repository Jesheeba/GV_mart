-- ── 3. Helpers ──────────────────────────────────────────────────────────────────────────────────────
-- When a ticket was finished: its invoice time (create_service_invoice completes the ticket in the same
-- statement), else the last visit's end, else the last update.
create or replace function public._ticket_completed_at(p_ticket_id uuid)
returns timestamptz language sql stable security definer set search_path = public as $$
  select coalesce(
    (select i.created_at from public.invoices i where i.id = t.invoice_id),
    (select max(v.timer_end) from public.service_visits v where v.ticket_id = t.id),
    t.updated_at)
  from public.service_tickets t where t.id = p_ticket_id
$$;

-- Reworks counted against a technician for a salary month (IST): free reworks they are responsible for,
-- completed that month, real customers only, minus escalations the master APPROVED. Rework-paid jobs
-- never count (owner P1). A pending escalation still counts until the master approves it.
create or replace function public.technician_rework_count(p_org_id uuid, p_technician_id uuid, p_period date)
returns integer language sql stable security definer set search_path = public as $$
  select count(*)::integer
  from public.service_tickets st
  join public.invoices i on i.id = st.invoice_id
  join public.customers c on c.id = st.customer_id
  where st.org_id = p_org_id
    and st.type::text = 'rework'
    and st.status = 'completed'
    and st.rework_outcome = 'free'
    and st.rework_responsible_technician_id = p_technician_id
    and not c.is_test
    and (i.created_at at time zone 'Asia/Kolkata')::date >= date_trunc('month', p_period)::date
    and (i.created_at at time zone 'Asia/Kolkata')::date < (date_trunc('month', p_period) + interval '1 month')::date
    and not exists (
      select 1 from public.approvals ap
      where ap.ref_id = st.id and ap.type::text = 'rework' and ap.status = 'approved')
$$;

-- ── 4. mark_ticket_rework ───────────────────────────────────────────────────────────────────────────
create or replace function public.mark_ticket_rework(
  p_ticket_id uuid,
  p_reason text,
  p_scheduled_date date,
  p_unavailable_windows jsonb default '[]'::jsonb,
  p_technician_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_org uuid := public.current_org_id();
  v_orig service_tickets;
  v_settings settings;
  v_existing uuid;
  v_last_visit service_visits;
  v_responsible uuid;
  v_assignee uuid;
  v_result jsonb;
  v_new_id uuid;
begin
  if not public.is_ops_staff() then
    raise exception 'mark_ticket_rework: only master or operation_admin may mark a rework';
  end if;
  if p_reason is null or length(btrim(p_reason)) < 5 then
    raise exception 'mark_ticket_rework: a reason of at least 5 characters is required';
  end if;

  -- Row lock serialises two people marking the same ticket at once; the unique index is the backstop.
  select * into v_orig from public.service_tickets where id = p_ticket_id and org_id = v_org for update;
  if v_orig.id is null then
    raise exception 'mark_ticket_rework: ticket % not found', p_ticket_id;
  end if;
  if v_orig.status <> 'completed' then
    raise exception 'mark_ticket_rework: only a completed ticket can be marked as rework';
  end if;

  select id into v_existing from public.service_tickets
    where rework_of_ticket_id = p_ticket_id and status <> 'cancelled' limit 1;
  if v_existing is not null then
    raise exception 'mark_ticket_rework: this ticket already has rework % - mark that ticket instead', v_existing;
  end if;

  select * into v_settings from public.settings where org_id = v_org;
  if v_settings is null then
    raise exception 'mark_ticket_rework: no settings row for org %', v_org;
  end if;
  if public._ticket_completed_at(p_ticket_id) < now() - make_interval(days => v_settings.rework_window_days) then
    raise exception 'mark_ticket_rework: completed more than % days ago - raise a new complaint instead', v_settings.rework_window_days;
  end if;

  -- Responsible = technician of the last finished visit (fixed here, never changed by a reassignment).
  select * into v_last_visit from public.service_visits
    where ticket_id = p_ticket_id order by timer_end desc nulls last, created_at desc limit 1;
  v_responsible := v_last_visit.technician_id;
  if v_responsible is null then
    raise exception 'mark_ticket_rework: ticket % has no visit, so no technician can be held responsible', p_ticket_id;
  end if;

  v_assignee := coalesce(p_technician_id, v_responsible);
  if not exists (select 1 from public.technicians where id = v_assignee and org_id = v_org and is_active) then
    if p_technician_id is not null then
      raise exception 'mark_ticket_rework: technician % not found or inactive', p_technician_id;
    end if;
    v_assignee := null; -- original technician left / deactivated: leave unassigned, ops are told below
  end if;

  -- Same scheduling + assignment path as every admin complaint (date, unavailable windows, busy checks).
  v_result := public._create_complaint_ticket_internal(
    v_org, v_orig.customer_id, v_orig.address_id, v_orig.product_id, v_orig.brand_id, v_orig.model_id,
    coalesce(v_orig.name_of_complaint, 'Rework'), btrim(p_reason), 'urgent'::priority_level, 'call'::ticket_channel,
    'datetime'::appointment_mode, false, p_scheduled_date, null, null, v_orig.unlisted_product_name,
    v_orig.complaint_type_id, coalesce(p_unavailable_windows, '[]'::jsonb), v_assignee
  );
  v_new_id := (v_result ->> 'ticket_id')::uuid;

  update public.service_tickets
    set type = 'rework',
        contract_id = null, warranty_id = null, rental_contract_id = null,
        estimated_duration_minutes = coalesce(v_orig.estimated_duration_minutes, estimated_duration_minutes),
        rework_of_ticket_id = p_ticket_id,
        rework_responsible_technician_id = v_responsible,
        rework_reason = btrim(p_reason),
        rework_raised_by = auth.uid(),
        rework_raised_at = now()
    where id = v_new_id;

  -- First-time-fix % (reports) finally sees the failed visit.
  update public.service_visits set needs_revisit = true where id = v_last_visit.id;

  if not coalesce((v_result -> 'assign_result' ->> 'assigned')::boolean, false) then
    insert into public.notifications (org_id, role, type, title, body, ref_id)
    values (v_org, 'operation_admin', 'rework_unassigned', 'Rework needs a technician',
      'A rework could not be given to the original technician. Open the ticket and assign it.', v_new_id);
  end if;

  return v_result || jsonb_build_object('rework_ticket_id', v_new_id, 'responsible_technician_id', v_responsible);
end;
$function$;

-- ── 5. Escalation: "this was not my fault" (technician -> master) ──────────────────────────────────
create or replace function public.request_rework_escalation(p_ticket_id uuid, p_reason text)
returns uuid
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_tech uuid := public.current_technician_id();
  v_ticket service_tickets;
  v_id uuid;
begin
  if v_tech is null then
    raise exception 'request_rework_escalation: caller is not a technician';
  end if;
  if p_reason is null or length(btrim(p_reason)) < 10 then
    raise exception 'request_rework_escalation: explain why in at least 10 characters';
  end if;

  select * into v_ticket from public.service_tickets
    where id = p_ticket_id and org_id = public.current_org_id() for update;
  if v_ticket.id is null or v_ticket.type::text <> 'rework' then
    raise exception 'request_rework_escalation: rework ticket % not found', p_ticket_id;
  end if;
  if v_ticket.rework_responsible_technician_id is distinct from v_tech then
    raise exception 'request_rework_escalation: only the technician held responsible can escalate';
  end if;
  if v_ticket.status <> 'completed' or v_ticket.rework_outcome is distinct from 'free' then
    raise exception 'request_rework_escalation: only a completed free rework can be escalated';
  end if;
  if exists (select 1 from public.approvals where ref_id = p_ticket_id and type::text = 'rework') then
    raise exception 'request_rework_escalation: already escalated';
  end if;

  update public.service_tickets set rework_escalation_reason = btrim(p_reason) where id = p_ticket_id;

  insert into public.approvals (org_id, type, ref_id, requested_by, status)
  values (v_ticket.org_id, 'rework', p_ticket_id, auth.uid(), 'pending')
  returning id into v_id;

  insert into public.notifications (org_id, role, type, title, body, ref_id)
  values (v_ticket.org_id, 'master', 'rework_escalation', 'Rework escalation to review',
    'A technician says a rework was not their fault. Review it in Approvals.', p_ticket_id);
  return v_id;
end;
$function$;

-- approvals_insert_staff lets any staff insert approvals directly; a pre-approved 'rework' row would
-- skip the master. Rework approvals are created only by request_rework_escalation (definer, bypasses RLS).
drop policy if exists approvals_rework_via_rpc_only on public.approvals;
create policy approvals_rework_via_rpc_only on public.approvals as restrictive for insert
  with check (type::text <> 'rework');

-- Decision = the existing master-only Approvals update. Tell the technician the outcome.
create or replace function public._trg_approvals_rework_decided()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.type::text = 'rework' and old.status = 'pending' and new.status in ('approved', 'rejected') then
    insert into public.notifications (org_id, user_id, type, title, body, ref_id)
    values (new.org_id, new.requested_by, 'rework_escalation_decided',
      case when new.status = 'approved' then 'Rework escalation approved' else 'Rework escalation rejected' end,
      case when new.status = 'approved' then 'The master agreed this rework was not your fault. It will not count against you.'
           else 'The master kept this as your rework. It still counts against you.' end,
      new.ref_id);
  end if;
  return new;
end $$;

drop trigger if exists approvals_rework_decided on public.approvals;
create trigger approvals_rework_decided after update of status on public.approvals
  for each row execute function public._trg_approvals_rework_decided();

-- ── 6. Ticket-level side effects ────────────────────────────────────────────────────────────────────
-- (a) Cancelling / deleting a rework clears needs_revisit on the original's visits.
-- (b) A free rework finishing while the master has not set the penalty rule is flagged (owner Q4).
create or replace function public._trg_service_tickets_rework_after()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_row service_tickets := case when tg_op = 'DELETE' then old else new end;
  v_settings settings;
begin
  if v_row.rework_of_ticket_id is null then
    return null;
  end if;

  if tg_op = 'DELETE' or (new.status = 'cancelled' and old.status is distinct from 'cancelled') then
    update public.service_visits set needs_revisit = false
      where ticket_id = v_row.rework_of_ticket_id and needs_revisit;
    return null;
  end if;

  if new.rework_outcome = 'free' and old.rework_outcome is distinct from 'free' then
    select * into v_settings from public.settings where org_id = new.org_id;
    if v_settings.rework_penalty_free_count is null or v_settings.rework_penalty_amount is null then
      insert into public.notifications (org_id, role, type, title, body, ref_id)
      values (new.org_id, 'master', 'rework_penalty_not_set', 'Rework penalty rule not set',
        'A rework was completed but no rework penalty is set, so no deduction will apply. Set it in Settings.', new.id);
    end if;
  end if;
  return null;
end $$;

drop trigger if exists service_tickets_rework_after on public.service_tickets;
create trigger service_tickets_rework_after after update or delete on public.service_tickets
  for each row execute function public._trg_service_tickets_rework_after();

-- ── 7. Report ───────────────────────────────────────────────────────────────────────────────────────
-- Per responsible technician, reworks completed in [p_from, p_to] (IST dates), real customers only.
create or replace function public.report_rework_summary(p_from date, p_to date)
returns table (
  technician_id uuid, technician_name text,
  free_reworks integer, paid_reworks integer, rework_minutes integer,
  escalations_pending integer, escalations_approved integer, escalations_rejected integer
)
language plpgsql stable security definer set search_path = public as $function$
begin
  if not public.is_ops_staff() then
    raise exception 'report_rework_summary: master or operation_admin only';
  end if;
  return query
  select st.rework_responsible_technician_id, p.full_name,
    count(*) filter (where st.rework_outcome = 'free')::integer,
    count(*) filter (where st.rework_outcome = 'paid')::integer,
    coalesce(sum((select sum(extract(epoch from (v.timer_end - v.timer_start)) / 60)
                  from public.service_visits v where v.ticket_id = st.id and v.timer_end is not null)), 0)::integer,
    count(ap.id) filter (where ap.status = 'pending')::integer,
    count(ap.id) filter (where ap.status = 'approved')::integer,
    count(ap.id) filter (where ap.status = 'rejected')::integer
  from public.service_tickets st
  join public.invoices i on i.id = st.invoice_id
  join public.customers c on c.id = st.customer_id
  join public.technicians t on t.id = st.rework_responsible_technician_id
  join public.profiles p on p.id = t.profile_id
  left join public.approvals ap on ap.ref_id = st.id and ap.type::text = 'rework'
  where st.org_id = public.current_org_id()
    and st.type::text = 'rework' and st.status = 'completed' and not c.is_test
    and (i.created_at at time zone 'Asia/Kolkata')::date between p_from and p_to
  group by st.rework_responsible_technician_id, p.full_name
  order by p.full_name;
end;
$function$;

-- ── 8. Re-issued live functions ─────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.create_service_invoice(p_org_id uuid, p_visit_id uuid, p_service_charge numeric, p_discount_percent numeric, p_spares jsonb, p_payment_method payment_method, p_txn_id text, p_payment_description text, p_is_chargeable boolean, p_amount_paid numeric DEFAULT NULL::numeric, p_installations jsonb DEFAULT '[]'::jsonb, p_gst_inclusive boolean DEFAULT NULL::boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_tech_id uuid;
  v_visit service_visits;
  v_ticket service_tickets;
  v_settings settings;
  v_subtotal numeric(12, 2) := 0;
  v_discount numeric(12, 2);
  v_gst numeric(12, 2);
  v_total numeric(12, 2);
  v_gst_inclusive boolean;
  v_amount_paid numeric(12, 2);
  v_invoice invoices;
  v_item record;
  v_price numeric(12, 2);
  v_cost numeric(12, 2);
  v_line_discount numeric(12, 2);
  v_new_stock integer;
  v_movement_reason text;
  v_approval_id uuid;
  v_effective_charge numeric(12, 2);
  v_amc_plan_id uuid;
  v_is_spare_covered boolean;
  v_rental_contract rental_contracts;
  v_rental_plan rental_plans;
  v_rental_interval_months integer;
  v_rental_visit_date date;
  v_rental_ticket_id uuid;
  v_rental_address_id uuid;
  v_install record; -- INSTALLATION TRACKING
  v_credit_qty integer;
begin
  v_tech_id := public.current_technician_id();
  if v_tech_id is null then
    raise exception 'create_service_invoice: caller is not a technician';
  end if;
  if p_org_id is distinct from public.current_org_id() then
    raise exception 'create_service_invoice: org mismatch';
  end if;

  select * into v_visit from public.service_visits where id = p_visit_id and org_id = p_org_id;
  if v_visit is null then
    raise exception 'create_service_invoice: visit % not found', p_visit_id;
  end if;
  if v_visit.technician_id is distinct from v_tech_id then
    raise exception 'create_service_invoice: visit % does not belong to the calling technician', p_visit_id;
  end if;

  select * into v_ticket from public.service_tickets where id = v_visit.ticket_id and org_id = p_org_id;
  if v_ticket is null then
    raise exception 'create_service_invoice: ticket for visit % not found', p_visit_id;
  end if;

  select * into v_settings from public.settings where org_id = p_org_id;
  if v_settings is null then
    raise exception 'create_service_invoice: no settings row for org %', p_org_id;
  end if;

  -- A completed ticket is never invoiced (or credited) twice. The same technician repeating the call (offline-queue replay)
  -- gets the existing invoice back and nothing else is written; anyone else gets an error.
  if v_ticket.status = 'completed' then
    if v_ticket.invoice_id is not null and v_visit.technician_id = v_tech_id then
      return jsonb_build_object('invoice_id', v_ticket.invoice_id,
        'total', (select i.total from public.invoices i where i.id = v_ticket.invoice_id),
        'approval_id', null, 'already_completed', true);
    end if;
    raise exception 'create_service_invoice: ticket % is already completed', v_ticket.id;
  end if;

  if p_discount_percent < 0 then
    raise exception 'create_service_invoice: discount cannot be negative';
  end if;
  if p_discount_percent > v_settings.discount_admin_max then
    raise exception 'create_service_invoice: discount % exceeds the admin limit of %', p_discount_percent, v_settings.discount_admin_max;
  end if;

  if p_payment_method = 'transfer'
     and (nullif(p_txn_id, '') is null or nullif(p_payment_description, '') is null) then
    raise exception 'create_service_invoice: bank transfer requires a transaction ID and description';
  end if;

  -- REWORK (20270101100100): the server, never the app, decides whether a rework visit is chargeable.
  -- Any service charge or any spare => rework-paid (owner Q1/Q2, no approval); nothing => free rework at 0.
  if v_ticket.type::text = 'rework' then
    p_is_chargeable := coalesce(p_service_charge, 0) > 0
      or (p_spares is not null and jsonb_typeof(p_spares) = 'array' and jsonb_array_length(p_spares) > 0);
    update public.service_tickets
      set rework_outcome = case when p_is_chargeable then 'paid' else 'free' end
      where id = v_ticket.id;
  end if;

  if v_ticket.type = 'amc' and v_ticket.contract_id is not null then
    select plan_id into v_amc_plan_id from public.amc_contracts where id = v_ticket.contract_id;
  end if;

  v_effective_charge := case when p_is_chargeable then coalesce(p_service_charge, 0) else 0 end;
  v_subtotal := v_effective_charge;

  if p_spares is not null and jsonb_array_length(p_spares) > 0 then
    for v_item in select * from jsonb_to_recordset(p_spares) as x(spare_id uuid, qty integer)
    loop
      if v_item.qty is null or v_item.qty <= 0 then
        raise exception 'create_service_invoice: qty must be positive for spare %', v_item.spare_id;
      end if;
      select price into v_price from public.spares where id = v_item.spare_id and org_id = p_org_id;
      if v_price is null then
        raise exception 'create_service_invoice: spare % not found in org %', v_item.spare_id, p_org_id;
      end if;
      v_is_spare_covered := v_amc_plan_id is null or exists (
        select 1 from public.amc_plan_covered_spares cs
        where cs.plan_id = v_amc_plan_id and cs.spare_id = v_item.spare_id
      );
      if p_is_chargeable or not v_is_spare_covered then
        v_subtotal := v_subtotal + (v_price * v_item.qty);
      end if;
    end loop;
  end if;

  v_discount := round(v_subtotal * p_discount_percent / 100, 2);
  v_gst_inclusive := coalesce(p_gst_inclusive, v_settings.prices_include_gst, false);
  v_gst := public._gst_amount(v_subtotal - v_discount, v_settings.gst_rate, v_gst_inclusive);
  v_total := v_subtotal - v_discount + case when v_gst_inclusive then 0 else v_gst end;

  v_amount_paid := coalesce(p_amount_paid, v_total);
  if v_amount_paid < 0 then
    raise exception 'create_service_invoice: amount_paid cannot be negative';
  end if;
  if v_amount_paid > v_total then
    raise exception 'create_service_invoice: amount_paid (%) cannot exceed the invoice total (%)', v_amount_paid, v_total;
  end if;

  insert into public.invoices (
    org_id, customer_id, type, subtotal, discount, gst, total, gst_inclusive,
    payment_method, txn_id, payment_description, payment_status, amount_paid
  ) values (
    p_org_id, v_ticket.customer_id, 'spare', v_subtotal, v_discount, v_gst, v_total, v_gst_inclusive,
    p_payment_method, nullif(p_txn_id, ''), nullif(p_payment_description, ''),
    public._derive_payment_status(v_amount_paid, v_total), v_amount_paid
  ) returning * into v_invoice;

  if p_spares is not null and jsonb_array_length(p_spares) > 0 then
    for v_item in select * from jsonb_to_recordset(p_spares) as x(spare_id uuid, qty integer)
    loop
      select price, cost_price into v_price, v_cost from public.spares where id = v_item.spare_id and org_id = p_org_id;
      v_is_spare_covered := v_amc_plan_id is null or exists (
        select 1 from public.amc_plan_covered_spares cs
        where cs.plan_id = v_amc_plan_id and cs.spare_id = v_item.spare_id
      );
      v_price := case when p_is_chargeable or not v_is_spare_covered then v_price else 0 end;
      v_line_discount := round(v_price * v_item.qty * p_discount_percent / 100, 2);

      insert into public.invoice_items (org_id, invoice_id, item_type, item_id, qty, price, discount, cost)
      values (p_org_id, v_invoice.id, 'spare', v_item.spare_id, v_item.qty, v_price, v_line_discount, v_cost);

      insert into public.service_spares_used (org_id, visit_id, spare_id, qty, cost)
      values (p_org_id, p_visit_id, v_item.spare_id, v_item.qty, v_price * v_item.qty);

      -- This technician's own van balance first (was the pooled, org-wide
      -- `inventory` location='van' row - see this migration's header).
      update public.technician_stock_levels
        set stock_qty = stock_qty - v_item.qty, updated_at = now()
        where org_id = p_org_id and technician_id = v_tech_id
          and item_type = 'spare' and item_id = v_item.spare_id and stock_qty >= v_item.qty
        returning stock_qty into v_new_stock;

      if v_new_stock is not null then
        v_movement_reason := 'service_use_van';
      else
        -- Van didn't cover it (never handed over, or not enough) - fall
        -- back to warehouse, same conditional UPDATE as before, but now
        -- tagged so Group 5 reporting can flag the shortfall distinctly
        -- from a normal van deduction.
        update public.inventory
          set stock_qty = stock_qty - v_item.qty
          where org_id = p_org_id and item_type = 'spare' and item_id = v_item.spare_id
            and location = 'warehouse' and stock_qty >= v_item.qty
          returning stock_qty into v_new_stock;
        v_movement_reason := 'service_use_shortfall';
      end if;
      if v_new_stock is null then
        raise exception 'create_service_invoice: insufficient stock for spare % (need %)', v_item.spare_id, v_item.qty;
      end if;

      insert into public.inventory_movements (org_id, item_type, item_id, change_qty, reason, ref_id, technician_id)
      values (p_org_id, 'spare', v_item.spare_id, -v_item.qty, v_movement_reason, p_visit_id, v_tech_id);

      -- NEW (requirement 6): a shortfall must be flagged for staff, not just tagged in the
      -- ledger. role='operation_admin' reaches master too via notifications_select_own_role's
      -- is_master() widening -- sales_admin, correctly, does not see it.
      if v_movement_reason = 'service_use_shortfall' then
        insert into public.notifications (org_id, role, type, title, body, ref_id)
        select p_org_id, 'operation_admin', 'spare_use_shortfall', 'Spare used with no recorded van stock',
          format('%s used %s x %s on a job without enough recorded van stock; drawn from the warehouse instead. Consider a hand-over.',
            coalesce(p.full_name, 'A technician'), v_item.qty, coalesce(s.name, 'a spare')),
          p_visit_id
        from public.technicians t
        join public.profiles p on p.id = t.profile_id
        left join public.spares s on s.id = v_item.spare_id
        where t.id = v_tech_id;
      end if;
    end loop;
  end if;

  -- INSTALLATION TRACKING: distinct from spares - logs which products were
  -- newly installed on this visit, purely for incentive counting (no
  -- invoice line, no stock movement - the product itself was already sold/
  -- stocked through its own path; this just credits the technician).
  if p_installations is not null and jsonb_array_length(p_installations) > 0 then
    for v_install in select * from jsonb_to_recordset(p_installations) as x(product_id uuid, qty integer)
    loop
      if v_install.qty is null or v_install.qty <= 0 then
        raise exception 'create_service_invoice: qty must be positive for installed product %', v_install.product_id;
      end if;
      if not exists (select 1 from public.products where id = v_install.product_id and org_id = p_org_id) then
        raise exception 'create_service_invoice: product % not found in org %', v_install.product_id, p_org_id;
      end if;

      insert into public.installations_logged (org_id, visit_id, technician_id, product_id, qty)
      values (p_org_id, p_visit_id, v_tech_id, v_install.product_id, v_install.qty);
    end loop;
  end if;

  -- Installation incentive: the ticket's per-unit charge (a master-editable snapshot) x units logged for the ticket's
  -- product, minimum 1. Created PENDING; the master approves it before Compute counts it. One credit per ticket+technician.
  if v_ticket.type = 'installation' and v_ticket.product_id is not null and coalesce(v_ticket.installation_charge_snapshot, 0) > 0 then
    select greatest(1, coalesce(sum(il.qty), 0))::integer into v_credit_qty
    from public.installations_logged il
    where il.visit_id = p_visit_id and il.product_id = v_ticket.product_id;
    insert into public.installation_incentive_credits (org_id, ticket_id, visit_id, technician_id, product_id, qty, unit_amount, amount, status)
    values (p_org_id, v_ticket.id, p_visit_id, v_tech_id, v_ticket.product_id, v_credit_qty,
            v_ticket.installation_charge_snapshot, v_ticket.installation_charge_snapshot * v_credit_qty, 'pending')
    on conflict (ticket_id, technician_id) do nothing;
    if found then
      insert into public.notifications (org_id, role, type, title, body, ref_id)
      values (p_org_id, 'master', 'installation_credit_pending', 'Installation incentive to approve',
              format('Installation completed: incentive of %s (%s unit(s)) is waiting for your approval.',
                     v_ticket.installation_charge_snapshot * v_credit_qty, v_credit_qty), v_ticket.id);
    end if;
  end if;

  update public.service_visits
    set service_charge = v_effective_charge, discount = p_discount_percent
    where id = p_visit_id;

  update public.service_tickets set status = 'completed', invoice_id = v_invoice.id where id = v_ticket.id;
  update public.appointments set status = 'completed'
    where ticket_id = v_ticket.id and technician_id = v_tech_id and status in ('scheduled', 'in_progress');

  if v_ticket.type = 'amc' and v_ticket.contract_id is not null then
    update public.amc_contracts
      set next_service_date = (
        select min((a.scheduled_at at time zone 'Asia/Kolkata')::date)
        from public.service_tickets st
        join public.appointments a on a.ticket_id = st.id
        where st.contract_id = v_ticket.contract_id
          and st.type = 'amc'
          and a.status in ('scheduled', 'in_progress')
      )
      where id = v_ticket.contract_id;
  end if;

  if v_ticket.type = 'warranty' and v_ticket.warranty_id is not null then
    update public.warranties
      set next_service_date = (
        select min((a.scheduled_at at time zone 'Asia/Kolkata')::date)
        from public.service_tickets st
        join public.appointments a on a.ticket_id = st.id
        where st.warranty_id = v_ticket.warranty_id
          and st.type = 'warranty'
          and a.status in ('scheduled', 'in_progress')
      )
      where id = v_ticket.warranty_id;
  end if;

  if v_ticket.type = 'rental' and v_ticket.rental_contract_id is not null then
    select * into v_rental_contract from public.rental_contracts where id = v_ticket.rental_contract_id;
    if v_rental_contract.status = 'active' then
      select * into v_rental_plan from public.rental_plans where id = v_rental_contract.plan_id;
      -- next visit: round(12 / visits_per_year) months from today (was integer division), rolled to a working day
      v_rental_interval_months := greatest(1, public._visit_month_offset(v_rental_plan.visits_per_year, 1));
      v_rental_visit_date := public._visit_working_day(p_org_id, ((now() at time zone 'Asia/Kolkata')::date + make_interval(months => v_rental_interval_months))::date);
      v_rental_address_id := coalesce(v_rental_contract.address_id, v_ticket.address_id);

      insert into public.service_tickets (
        org_id, customer_id, address_id, product_id, name_of_complaint, nature_of_complaint,
        type, priority, status, channel, rental_contract_id
      ) values (
        p_org_id, v_rental_contract.customer_id, v_rental_address_id, v_rental_contract.product_id,
        'Rental scheduled service', v_rental_plan.name, 'rental', 'normal', 'open', 'walk_in', v_rental_contract.id
      )
      returning id into v_rental_ticket_id;

      insert into public.appointments (org_id, ticket_id, mode, scheduled_at, available_from, available_to, status)
      values (p_org_id, v_rental_ticket_id, 'datetime', public._visit_start_ts(p_org_id, v_rental_visit_date),
              public._visit_window_from(p_org_id), public._visit_window_to(p_org_id), 'scheduled');

      perform public._auto_assign_ticket_internal(v_rental_ticket_id, p_org_id, p_skip_rating_logic => true);

      update public.rental_contracts set next_service_date = v_rental_visit_date where id = v_rental_contract.id;
    end if;
  end if;

  if p_discount_percent > v_settings.discount_tech_max then
    insert into public.approvals (org_id, type, ref_id, requested_by, status)
    values (p_org_id, 'discount', v_invoice.id, auth.uid(), 'pending')
    returning id into v_approval_id;
  end if;

  if (now() at time zone 'Asia/Kolkata')::time >= v_settings.work_end then
    update public.attendance
    set shift_end_prompt_pending = true
    where technician_id = v_tech_id and org_id = p_org_id
      and date = (now() at time zone 'Asia/Kolkata')::date;

    insert into public.notifications (org_id, user_id, type, title, body, ref_id)
    select p_org_id, p.id, 'shift_end_prompt', 'Shift end reached',
      format('Your shift ended at %s. Reply to continue or check out.', to_char(v_settings.work_end, 'HH12:MI AM')), v_invoice.id
    from public.technicians t join public.profiles p on p.id = t.profile_id
    where t.id = v_tech_id;
  else
    perform public._auto_assign_next_ticket_to_technician(p_org_id, v_tech_id);
  end if;

  return jsonb_build_object('invoice_id', v_invoice.id, 'total', v_total, 'approval_id', v_approval_id);
end;
$function$;

create or replace function public._auto_assign_next_ticket_to_technician(p_org_id uuid, p_technician_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_tech technicians;
  v_appointment_id uuid;
  v_ticket_id uuid;
  v_ticket service_tickets;
  v_settings settings;
  v_sla_hours numeric;
  v_tech_name text;
begin
  select * into v_tech from public.technicians where id = p_technician_id and org_id = p_org_id;
  if v_tech.id is null or not v_tech.is_active then
    return jsonb_build_object('assigned', false, 'reason_key', 'service.assign.technicianInactive');
  end if;

  -- free for the next job unless something overlaps right now (was: any open appointment of any date)
  if public._tech_busy_at(p_technician_id, now(), 1, null) then
    return jsonb_build_object('assigned', false, 'reason_key', 'service.assign.alreadyBusy');
  end if;

  if not exists (
    select 1 from public.attendance a
    where a.technician_id = p_technician_id and a.org_id = p_org_id and a.date = (now() at time zone 'Asia/Kolkata')::date
      and a.check_in_at is not null and a.check_out_at is null
  ) then
    return jsonb_build_object('assigned', false, 'reason_key', 'service.assign.notPresent');
  end if;

  select a.id, a.ticket_id into v_appointment_id, v_ticket_id
  from public.appointments a
  join public.service_tickets st on st.id = a.ticket_id
  left join public.addresses addr on addr.id = st.address_id
  left join lateral (
    select tl.lat, tl.lng from public.technician_locations tl
    where tl.technician_id = p_technician_id order by tl.recorded_at desc limit 1
  ) loc on true
  where a.org_id = p_org_id
    and a.technician_id is null
    and a.status in ('scheduled', 'in_progress')
    and st.status = 'open'
    and st.type::text is distinct from 'rework' -- REWORK: stays with its technician unless ops reassign
    and (st.product_id is not null or st.unlisted_product_name is not null)
    and not public._tech_busy_at(p_technician_id, coalesce(a.scheduled_at, now()), public._ticket_minutes(st.id), a.id)
    and (a.scheduled_at is null or (a.scheduled_at at time zone 'Asia/Kolkata')::date <= (now() at time zone 'Asia/Kolkata')::date)
    and coalesce((
      select sum(public._ticket_minutes(st2.id))
      from public.appointments a2
      join public.service_tickets st2 on st2.id = a2.ticket_id
      where a2.technician_id = p_technician_id
        and a2.status in ('scheduled', 'in_progress')
        and (a2.scheduled_at at time zone 'Asia/Kolkata')::date = coalesce((a.scheduled_at at time zone 'Asia/Kolkata')::date, (now() at time zone 'Asia/Kolkata')::date)
    ), 0) + public._ticket_minutes(st.id) <= v_tech.daily_capacity_minutes
  order by
    case st.priority when 'very_urgent' then 0 when 'urgent' then 1 else 2 end asc,
    case when loc.lat is not null and addr.lat is not null and addr.lng is not null
      then point(loc.lng, loc.lat) <-> point(addr.lng, addr.lat)
      else null
    end asc nulls last,
    coalesce(a.scheduled_at, st.created_at) asc
  for update of a skip locked
  limit 1;

  if v_appointment_id is null then
    return jsonb_build_object('assigned', false, 'reason_key', 'service.assign.noneWaiting');
  end if;

  update public.appointments set technician_id = p_technician_id, follow_up_flagged_at = null where id = v_appointment_id;
  update public.service_tickets set status = 'assigned' where id = v_ticket_id;

  select * into v_ticket from public.service_tickets where id = v_ticket_id;
  select * into v_settings from public.settings where org_id = p_org_id;
  v_sla_hours := case v_ticket.priority
    when 'very_urgent' then v_settings.sla_hours_very_urgent
    when 'urgent' then v_settings.sla_hours_urgent
    else v_settings.sla_hours_normal
  end;
  update public.service_tickets
  set assigned_at = now(),
      sla_due_at = (select greatest(now(), coalesce(a9.scheduled_at, now())) from public.appointments a9 where a9.id = v_appointment_id)
                   + v_sla_hours * interval '1 hour'
  where id = v_ticket_id;

  select p.full_name into v_tech_name
  from public.technicians t join public.profiles p on p.id = t.profile_id
  where t.id = p_technician_id;

  insert into public.notifications (org_id, user_id, type, title, body, ref_id)
  select p_org_id, p.id, 'appointment_assigned', 'New job assigned',
         format('Ticket %s assigned to you.', v_ticket_id), v_appointment_id
  from public.technicians t join public.profiles p on p.id = t.profile_id
  where t.id = p_technician_id;

  insert into public.notifications (org_id, role, type, title, body, ref_id)
  values (p_org_id, 'operation_admin', 'ticket_auto_assigned', 'Ticket auto-assigned',
    format('%s auto-assigned to %s.', coalesce(v_ticket.name_of_complaint, 'Ticket ' || v_ticket_id), coalesce(v_tech_name, 'a technician')),
    v_ticket_id);

  return jsonb_build_object('assigned', true, 'technician_id', p_technician_id, 'appointment_id', v_appointment_id, 'ticket_id', v_ticket_id);
end;
$function$;

create or replace function public._next_ticket_available_for_technician(p_org_id uuid, p_technician_id uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select exists (
    select 1
    from public.appointments a
    join public.service_tickets st on st.id = a.ticket_id
    join public.technicians t on t.id = p_technician_id
    where a.org_id = p_org_id
      and a.technician_id is null
      and a.status in ('scheduled', 'in_progress')
      and st.status = 'open'
      and st.type::text is distinct from 'rework' -- REWORK
      and (st.product_id is not null or st.unlisted_product_name is not null)
      and not public._tech_busy_at(p_technician_id, now(), 1, null)
      and not public._tech_busy_at(p_technician_id, coalesce(a.scheduled_at, now()), public._ticket_minutes(st.id), a.id)
      and (a.scheduled_at is null or (a.scheduled_at at time zone 'Asia/Kolkata')::date <= (now() at time zone 'Asia/Kolkata')::date)
      and coalesce((
        select sum(public._ticket_minutes(st2.id))
        from public.appointments a2
        join public.service_tickets st2 on st2.id = a2.ticket_id
        where a2.technician_id = p_technician_id
          and a2.status in ('scheduled', 'in_progress')
          and (a2.scheduled_at at time zone 'Asia/Kolkata')::date = coalesce((a.scheduled_at at time zone 'Asia/Kolkata')::date, (now() at time zone 'Asia/Kolkata')::date)
      ), 0) + public._ticket_minutes(st.id) <= t.daily_capacity_minutes
  );
$function$;

