-- snapshot at creation (one place, instead of patching every sale function)
create function public._trg_installation_charge_snapshot()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.type::text = 'installation' and new.installation_charge_snapshot is null and new.product_id is not null then
    select p.installation_charge into new.installation_charge_snapshot from public.products p where p.id = new.product_id;
  end if;
  return new;
end;
$$;
revoke execute on function public._trg_installation_charge_snapshot() from public, anon, authenticated;
create trigger service_tickets_installation_snapshot before insert on public.service_tickets
  for each row execute function public._trg_installation_charge_snapshot();

-- only the master (or a service-role/SQL session) may change the snapshot, and only before the ticket is closed
create function public._trg_installation_charge_guard()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.installation_charge_snapshot is distinct from old.installation_charge_snapshot
     and auth.uid() is not null and not public.is_master() then
    raise exception 'only the master can change an installation charge';
  end if;
  if new.installation_charge_snapshot is distinct from old.installation_charge_snapshot
     and auth.uid() is not null and old.status::text in ('completed', 'cancelled') then
    raise exception 'the installation charge of a closed ticket cannot be changed';
  end if;
  return new;
end;
$$;
revoke execute on function public._trg_installation_charge_guard() from public, anon, authenticated;
create trigger service_tickets_installation_guard before update of installation_charge_snapshot on public.service_tickets
  for each row execute function public._trg_installation_charge_guard();

