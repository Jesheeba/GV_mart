-- Installation incentive per ticket (2026-10-16) - batch-2 item 3 (design: docs/plan-batch2-design.md section 1).
--
-- DEPENDS ON 20261016110000_test_customer_flag (compute_incentives below is built on its body and uses _ticket_is_test).
-- The migration refuses to run before it.
--
--   * products.installation_charge   : master-editable per-unit amount, technician incentive only (never billed). NULL/0 = none.
--     products are already master-write only (RLS products_write_master).
--   * service_tickets.installation_charge_snapshot : filled from the product when an installation ticket is created; only the
--     master may edit it, and only until the ticket is completed/cancelled (set_ticket_installation_charge). Audited by the
--     existing audit trigger.
--   * installation_incentive_credits : one row per installation ticket (UNIQUE ticket+technician): amount = snapshot x units
--     logged (min 1), status pending -> approved | void. Written only by create_service_invoice; the master approves or voids
--     each one (approve_installation_credit / void_installation_credit). Technician sees their own, master sees all.
--   * compute_incentives : sums the APPROVED credits completed in the month into one incentives_earned row per technician and
--     month (new credit_source column; the exactly-one-source check is extended). A logged unit that has a pending/approved
--     credit is skipped by the per-unit rates, so nothing is paid twice. The flat monthly installation rule is untouched: turn it
--     off with its is_active switch (Masters > Incentive rules) when you start using charges, or it stacks on top.
--   * create_service_invoice : refuses to invoice a completed ticket twice (same technician repeating the call gets the existing
--     invoice back - offline-queue replay), creates the credit, notifies the master. The legacy 10-argument overload (no
--     installations parameter, never called by the app) is dropped.
-- No existing number changes until a charge is set on a product (0 incentive rows exist today).

do $guard$
begin
  if to_regprocedure('public._ticket_is_test(uuid)') is null then
    raise exception 'apply 20261016110000_test_customer_flag before this migration (compute_incentives is built on its body)';
  end if;
end;
$guard$;

