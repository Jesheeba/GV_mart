-- master actions -------------------------------------------------------------------------------------------------------
create function public.set_ticket_installation_charge(p_ticket_id uuid, p_amount numeric)
returns void language plpgsql security definer set search_path = public as $$
declare v_t public.service_tickets;
begin
  if not public.is_master() then raise exception 'set_ticket_installation_charge: master role required'; end if;
  select * into v_t from public.service_tickets where id = p_ticket_id;
  if v_t.id is null or v_t.org_id is distinct from public.current_org_id() then
    raise exception 'set_ticket_installation_charge: ticket not found';
  end if;
  if v_t.type::text <> 'installation' then
    raise exception 'set_ticket_installation_charge: only installation tickets carry an installation charge';
  end if;
  if p_amount is not null and p_amount < 0 then
    raise exception 'set_ticket_installation_charge: amount cannot be negative';
  end if;
  update public.service_tickets set installation_charge_snapshot = p_amount where id = p_ticket_id;
end;
$$;

create function public.approve_installation_credit(p_credit_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare v_c public.installation_incentive_credits;
begin
  if not public.is_master() then raise exception 'approve_installation_credit: master role required'; end if;
  select * into v_c from public.installation_incentive_credits where id = p_credit_id for update;
  if v_c.id is null or v_c.org_id is distinct from public.current_org_id() then
    raise exception 'approve_installation_credit: credit not found';
  end if;
  if v_c.status <> 'pending' then
    raise exception 'approve_installation_credit: credit is already %', v_c.status;
  end if;
  update public.installation_incentive_credits
  set status = 'approved', approved_by = auth.uid(), approved_at = now() where id = p_credit_id;
end;
$$;

create function public.void_installation_credit(p_credit_id uuid, p_reason text)
returns void language plpgsql security definer set search_path = public as $$
declare v_c public.installation_incentive_credits;
begin
  if not public.is_master() then raise exception 'void_installation_credit: master role required'; end if;
  select * into v_c from public.installation_incentive_credits where id = p_credit_id for update;
  if v_c.id is null or v_c.org_id is distinct from public.current_org_id() then
    raise exception 'void_installation_credit: credit not found';
  end if;
  if v_c.status = 'void' then
    raise exception 'void_installation_credit: credit is already void';
  end if;
  if nullif(btrim(coalesce(p_reason, '')), '') is null then
    raise exception 'void_installation_credit: a reason is required';
  end if;
  update public.installation_incentive_credits
  set status = 'void', voided_by = auth.uid(), voided_at = now(), void_reason = btrim(p_reason) where id = p_credit_id;
end;
$$;

